export const PROVIDERS_BY_ID: Record<ConnectionProvider, ProviderMeta> =
  Object.fromEntries(PROVIDERS.map((p) => [p.id, p])) as Record<
    ConnectionProvider,
    ProviderMeta
  >;

export function providerMeta(id: string): ProviderMeta | undefined {
  return PROVIDERS_BY_ID[id as ConnectionProvider];
}

export function providerName(id: string): string {
  return providerMeta(id)?.name ?? id;
}

/** Categories that actually have entries, in display order. */
export function activeCategories(metas: ProviderMeta[] = PROVIDERS): ProviderCategory[] {
  const present = new Set(metas.map((m) => m.category));
  return PROVIDER_CATEGORIES.filter((c) => present.has(c));
}

/** Short list offered during onboarding. */
export const CORE_PROVIDERS: ProviderMeta[] = PROVIDERS.filter((p) => p.core);
