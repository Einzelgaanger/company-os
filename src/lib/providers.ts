/**
 * How an admin proves the workspace owns the account.
 *  oauth2  — redirect handshake, PKCE, refresh tokens (preferred)
 *  api_key — provider-issued read token pasted once, encrypted at rest
 *  webhook — provider pushes to a per-tenant signed endpoint; nothing to poll
 */
export type ProviderAuth = "oauth2" | "api_key" | "webhook";

export interface ProviderMeta {
  id: ConnectionProvider;
  name: string;
  category: ProviderCategory;
  auth: ProviderAuth;
  /** Org-level connections are shared by the workspace; others are per person. */
  orgLevel?: boolean;
  /** What Company OS reads. Plain language — this string is shown to users. */
  reads: string;
  /** Read-only scopes or permissions requested. */
  scopesNote: string;
  /** Iconify name for the brand mark. */
  icon: string;
  /** Provider-side setup docs for whoever creates the credentials. */
  docsUrl: string;
  /** Offered during onboarding; the rest live on /integrations. */
  core?: boolean;
}

