#!/usr/bin/env node
/**
 * Projects the OAuth half of apps/api/src/lib/providerRegistry.ts into a Deno
 * module for the Supabase edge plane, so production (Supabase) and the Fastify
 * stack cannot disagree about a provider's endpoints.
 *
 * Usage: node scripts/gen/edge-providers.mjs   (also checked by check:connectors)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../..");
export const OUT_FILE = join(
  ROOT,
  "supabase",
  "functions",
  "_shared",
  "providers.generated.ts",
);

export async function buildEdgeProviders() {
  const { CONNECTORS } = await import(
    pathToFileURL(join(ROOT, "apps", "api", "src", "lib", "providerRegistry.ts")).href
  );

  const entries = CONNECTORS.filter((c) => c.auth === "oauth2").map((c) => ({
    id: c.id,
    name: c.name,
    orgLevel: c.orgLevel,
    clientIdSecret: c.clientIdEnv,
    clientSecretSecret: c.clientSecretEnv,
    instanceSecret: c.instanceEnv ?? null,
    featureFlag: c.featureFlag ?? null,
    authorizeUrl: c.oauth.authorizeUrl,
    tokenUrl: c.oauth.tokenUrl,
    scopes: c.oauth.scopes,
    clientAuth: c.oauth.clientAuth,
    pkce: c.oauth.pkce,
    authorizeParams: c.oauth.authorizeParams ?? {},
    jsonAccept: Boolean(c.oauth.jsonAccept),
    identityUrl: c.oauth.identityUrl ?? null,
    identityPath: c.oauth.identityPath ?? null,
    identityFromToken: c.oauth.identityFromToken ?? null,
  }));

  const body = entries
    .map((e) => `  ${JSON.stringify(e.id)}: ${JSON.stringify(e, null, 2).replace(/\n/g, "\n  ")},`)
    .join("\n");

  return `// GENERATED by scripts/gen/edge-providers.mjs — do not edit.
// Source of truth: apps/api/src/lib/providerRegistry.ts
// Regenerate with: node scripts/gen/edge-providers.mjs

export interface EdgeConnector {
  id: string;
  name: string;
  orgLevel: boolean;
  clientIdSecret: string;
  clientSecretSecret: string;
  instanceSecret: string | null;
  featureFlag: string | null;
  authorizeUrl: string;
  tokenUrl: string;
  scopes: string[];
  clientAuth: "body" | "basic";
  pkce: boolean;
  authorizeParams: Record<string, string>;
  jsonAccept: boolean;
  identityUrl: string | null;
  identityPath: string[] | null;
  identityFromToken: string[] | null;
}

export const EDGE_CONNECTORS: Record<string, EdgeConnector> = {
${body}
};

export const EDGE_PROVIDER_IDS = Object.keys(EDGE_CONNECTORS);
`;
}

export function currentEdgeProviders() {
  try {
    return readFileSync(OUT_FILE, "utf8").replace(/\r\n/g, "\n");
  } catch {
    return null;
  }
}

const invokedDirectly =
  process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;

if (invokedDirectly) {
  const next = await buildEdgeProviders();
  writeFileSync(OUT_FILE, next, "utf8");
  const count = (next.match(/"authorizeUrl"/g) ?? []).length;
  console.log(`edge-providers: wrote ${count} OAuth connectors to ${OUT_FILE}`);
}
