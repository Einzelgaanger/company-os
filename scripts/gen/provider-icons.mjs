#!/usr/bin/env node
/**
 * Vendors the brand mark for every connector in src/lib/providers.ts into
 * public/integrations/<id>.svg.
 *
 * Sources (both redistributable, both offline once installed):
 *   logos        — SVG Logos by Gil Barbara, CC0-1.0
 *   thesvg-color — thesvg.org, MIT
 *
 * Icons are vendored rather than fetched at runtime so the Integrations page
 * has no third-party requests and works offline.
 *
 * Usage:
 *   npm i --no-save @iconify/json && node scripts/gen/provider-icons.mjs
 *
 * A connector with `icon: ""` gets no file — the UI falls back to a lettermark
 * (used where no brand mark is redistributable).
 */
import { createRequire } from "node:module";
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../..");
const CATALOG = join(ROOT, "src", "lib", "providers.ts");
const OUT_DIR = join(ROOT, "public", "integrations");

const require = createRequire(import.meta.url);

function loadSet(prefix) {
  let file;
  try {
    file = require.resolve(`@iconify/json/json/${prefix}.json`);
  } catch {
    console.error(
      `provider-icons: @iconify/json is not installed.\n` +
        `  Run: npm i --no-save @iconify/json && node scripts/gen/provider-icons.mjs`,
    );
    process.exit(1);
  }
  return JSON.parse(readFileSync(file, "utf8"));
}

/** id + icon pairs, in catalog order. */
function parseCatalog() {
  const src = readFileSync(CATALOG, "utf8");
  const entries = [];
  const blocks = src.matchAll(
    /\bid:\s*"([a-z0-9_]+)",[\s\S]*?\bicon:\s*"([^"]*)"/g,
  );
  for (const m of blocks) entries.push({ id: m[1], icon: m[2] });
  if (entries.length === 0) {
    console.error("provider-icons: parsed 0 connectors from src/lib/providers.ts");
    process.exit(1);
  }
  return entries;
}

const sets = new Map();
function iconData(ref) {
  const at = ref.lastIndexOf(":");
  const prefix = ref.slice(0, at);
  const name = ref.slice(at + 1);
  if (!sets.has(prefix)) sets.set(prefix, loadSet(prefix));
  const set = sets.get(prefix);

  let icon = set.icons?.[name];
  if (!icon) {
    const alias = set.aliases?.[name];
    if (alias?.parent) icon = set.icons?.[alias.parent];
    if (alias && (alias.hFlip || alias.vFlip || alias.rotate)) {
      throw new Error(`${ref} is a transformed alias — point at the base icon instead`);
    }
  }
  if (!icon) throw new Error(`${ref} does not exist in the ${prefix} set`);
  if (/currentColor/.test(icon.body)) {
    throw new Error(`${ref} is monochrome (currentColor) — pick a full-colour mark`);
  }

  const width = icon.width ?? set.width ?? 24;
  const height = icon.height ?? set.height ?? 24;
  const left = icon.left ?? 0;
  const top = icon.top ?? 0;
  return { body: icon.body, viewBox: `${left} ${top} ${width} ${height}` };
}

const entries = parseCatalog();

rmSync(OUT_DIR, { recursive: true, force: true });
mkdirSync(OUT_DIR, { recursive: true });

const written = [];
const skipped = [];
const failures = [];

for (const { id, icon } of entries) {
  if (!icon) {
    skipped.push(id);
    continue;
  }
  try {
    const { body, viewBox } = iconData(icon);
    const svg =
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" role="img" aria-hidden="true">` +
      `<!-- ${icon} -->${body}</svg>\n`;
    writeFileSync(join(OUT_DIR, `${id}.svg`), svg, "utf8");
    written.push(id);
  } catch (e) {
    failures.push(`${id}: ${e.message}`);
  }
}

writeFileSync(
  join(OUT_DIR, "SOURCES.md"),
  [
    "# Vendored connector brand marks",
    "",
    "Generated by `scripts/gen/provider-icons.mjs` — do not edit by hand.",
    "",
    "| Connector | Iconify source |",
    "| --- | --- |",
    ...entries
      .filter((e) => e.icon)
      .map((e) => `| \`${e.id}\` | \`${e.icon}\` |`),
    "",
    "Sets: [`logos`](https://github.com/gilbarbara/logos) (CC0-1.0),",
    "[`thesvg-color`](https://github.com/glincker/thesvg) (MIT).",
    "Brand marks remain the property of their respective owners and are used here",
    "to identify the service being connected.",
    "",
  ].join("\n"),
  "utf8",
);

if (failures.length > 0) {
  console.error(`provider-icons: FAIL\n  · ${failures.join("\n  · ")}`);
  process.exit(1);
}

const stray = readdirSync(OUT_DIR).filter(
  (f) => f.endsWith(".svg") && !written.includes(f.replace(/\.svg$/, "")),
);

console.log(
  `provider-icons: wrote ${written.length} marks` +
    (skipped.length ? `, lettermark fallback for ${skipped.join(", ")}` : "") +
    (stray.length ? `, stray files: ${stray.join(", ")}` : ""),
);
